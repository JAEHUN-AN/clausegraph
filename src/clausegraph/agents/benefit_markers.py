"""급여ㆍ비급여 구분 표지 — 청구 서술이 '비급여'ㆍ'급여'라고 말하는가.

의료행위가 아니라 **건강보험 급여 구분**을 가리키는 말을 찾는다. 급여 실손은 비급여를
(제4조의2), 비급여 특약은 급여를(제3조) 보상하지 않으므로 이 말이 있으면 (1)(2) 산식으로
계산하지 않고 사람에게 보낸다(notes/049ㆍ050). 어느 상품이 무엇을 빼는지, 사유에 어느 조문을
적는지는 `amount_rules`가 정한다. 여기는 글에서 말을 찾고 그 낱말을 돌려줄 뿐이다.

3대비급여ㆍ비급여 MRI 표지(`amount_rules`)도 이 모듈의 `clean`ㆍ`word_at`을 거친다.
"""

from __future__ import annotations

import re
import unicodedata

from .extract import parse_amounts

# 사유에 낱말을 적을 때 떼는 조사 — '도수치료를'이 아니라 '도수치료'.
_PARTICLE_RE = re.compile(r"(?:으로|에서|에게|까지|부터|를|을|이|가|은|는|와|과|도|만|에|의|로)$")


# 지울 한글 채움 문자(U+115Fㆍ1160ㆍ3164). NFKC가 U+3164ㆍFFA0을 U+1160으로 바꾸지만 셋 다 둔다.
_HANGUL_FILLERS = frozenset(map(chr, (0x115F, 0x1160, 0x3164)))
# 서식(Cf)ㆍ결합(MnㆍMe) 문자, 그리고 사설 영역(Co) — `_MASK`가 사설 영역 글자라 입력에서
# 먼저 지운다.
_INVISIBLE_CATEGORIES = frozenset({"Cf", "Mn", "Me", "Co"})
# NFKC가 가운뎃점 'ㆍ'(U+318D)를 바꿔 놓는 글자(U+119E).
_NFKC_MIDDLE_DOT = chr(0x119E)


def clean(text: str) -> str:
    """NFKC로 모으고 눈에 안 보이는 문자를 지운 뒤 다시 모은다.

    "도(U+200B)수치료", "비(U+200B)급여"처럼 눈에 안 보이는 문자가 표지를 끊으면 (1)(2)로 계산된다.
    서식 문자(Cf — 폭 없는 공백ㆍBOMㆍ소프트 하이픈)만 지우던 첫 판은 결합 문자(Mn — U+034Fㆍ
    U+0301ㆍ변형 선택자)와 한글 채움 문자(U+3164)를 끼운 "급(U+034F)여 본인부담금만"을 놓쳤다(반박
    검토, notes/050). 지운 뒤 다시 모으는 것은 쪼갠 자모 사이에 끼운 경우 때문이다.
    """
    normalized = unicodedata.normalize("NFKC", text)
    visible = "".join(
        ch
        for ch in normalized
        if unicodedata.category(ch) not in _INVISIBLE_CATEGORIES and ch not in _HANGUL_FILLERS
    )
    return unicodedata.normalize("NFKC", visible)


def word_at(text: str, start: int, end: int) -> str:
    """표지를 품은 낱말 전체 — 사유에 '주사'가 아니라 '영양주사'로 적는다."""
    left, right = start, end
    while left > 0 and text[left - 1].isalnum():
        left -= 1
    while right < len(text) and text[right].isalnum():
        right += 1
    word = text[left:right]
    particle = _PARTICLE_RE.search(word)
    # 표지 자체를 깎지는 않는다 — '엠알아이'의 '이'는 조사가 아니다.
    if particle is not None and left + particle.start() >= end:
        word = word[: particle.start()]
    return word


# 급여 실손 제4조의2(특별약관에서 보상하는 사항)
#
#   ① "제3조 및 제4조에도 불구하고 다음 각 호에 해당하는 의료비는 기본형
#      실손의료보험에서 보상하지 않습니다. 1. 비급여 의료비 …"
#   ② "… 다른 의료비가 함께 청구되어 각 항목별 의료비가 구분되지 않는 경우 회사는 …
#      각각의 의료비에 대한 확인을 요청할 수 있습니다."
#
# 이 조문은 면책(`Article:Exclusion`)이 아니라 면책 검증이 열거하지 않는다. 그래서
# "비급여 도수치료 통원" 급여 실손 청구가 (2)질병급여로 확정됐다 — 의원ㆍ본인부담률
# 0.3이면 10만원에 7만원, 입원 100만원이면 80만원(notes/049).
#
# 의료행위 이름(도수치료ㆍMRIㆍ주사)으로는 가르지 않는다 — 급여 MRIㆍ급여 주사는 급여
# 의료비다(notes/048). 청구인이 "비급여"라고 말한 것만 본다.
#
# - 붙여 쓴 "비급여"(와 "비급 여")는 어디서나. 기호ㆍ띄어쓰기를 끼운 꼴("비 급여", "비-급여",
#   "비ㆍ급여", "(비)급여")은 '비'가 홀로 섰을 때만 — "치료비 급여 항목"의 '비'는 '치료비'의 것이다.
# - "비보험"도 '비'가 홀로 섰을 때만. 실제 분쟁 문장 160건에서 "비 보험" 4건이 모두 "진단비
#   보험금"ㆍ"수리비 보험금"이었다 — 앞이 한글인 '비'다. "실비보험"도 같은 이유로 거른다.
# - 한자 "非給與". 폭 없는 문자ㆍBOMㆍ소프트 하이픈은 `clean`이 먼저 지운다.
#
# 처음엔 `비급여|(?<![가-힣])비\s+급여`였다. 반박 검토에서 폭 없는 공백(U+200B)을 끼운
# "비급여"ㆍ"비-급여"ㆍ"非給與"ㆍ"비보험"이 빠져나가 급여 입원 100만원에 800,000원이 그대로
# 나갔다(notes/049).
# "건강보험 적용 안 되는" 같은 풀어 쓴 말은 읽지 않는다.
_NONCOVERED_SEP = r"[\s\-·ㆍᆞ・‧()\[\]]*"
_NONCOVERED_RE = re.compile(
    r"비급\s*여"
    rf"|(?<![가-힣])비{_NONCOVERED_SEP}(?:급{_NONCOVERED_SEP}여|보험)"
    r"|非\s*(?:給\s*與|급\s*여)"
)

# 비급여 특약(특약1ㆍ2) 제3조 (1)(2) ①
#
#   "… 비급여의료비(3대비급여는 제외합니다)를 … 보상합니다"(특약1)
#   "… 비급여의료비(비급여 자기공명영상진단은 제외합니다)를 … 보상합니다"(특약2)
#
# 보상 대상은 비급여 의료비뿐이고, 급여 본인부담금은 기본형(급여 실손)이 보상한다. 위
# '비급여'의 거울상이다 — "비급여 항목 없음, 급여 본인부담금만 진료비 100만원" 특약 청구가
# (2)질병비급여로 계산돼 특약1 700,000원, 특약2 500,000원이 나갔다(notes/050).
#
# '급여'라는 말 하나로는 가르지 않는다. 실제 분쟁 문장 160건 전문에서 '비급여' 아닌 '급여'
# 37곳은 요양급여ㆍ의료급여(수급권자)ㆍ"지급 여부"ㆍ휴업급여금이 대부분이었다. **급여 몫을
# 가리키는 짝**만 본다.
#
# - 급여 + 본인(환자)부담 — "급여 본인부담금", "급여의 본인부담금", "급여 일부본인부담",
#   "요양급여 중 본인부담". 요양ㆍ의료ㆍ보험 뒤에 붙어도 받는다. "건강보험 본인부담금"도.
# - 영수증의 급여 칸 이름 — ① 본인일부부담금, ② 공단부담금(보험자부담금). 급여에만 있다.
# - 급여 + 항목ㆍ부분ㆍ의료비ㆍ진료(비)ㆍ치료(비), 급여분ㆍ급여만. 띄어 쓴 "급 여"도 받는다 —
#   앞이 한글이면 막으므로 "지급 여부"는 걸리지 않는다.
# - 급여와 비급여를 함께 적은 꼴 — "급여ㆍ비급여 합계", "비급여와 급여", "급여 80만원,
#   비급여 20만원", "100만원 중 비급여 30만원", "비급여 30만원 포함". 급여 몫을 나눠야 한다.
# - 홀로 선 '비급여'가 없다는 말 — "비급여 항목 없음", "비급여: 없음", "비급여가 아닙니다",
#   "비급여 0원", "비급여 제외". 남는 것은 급여다. 049처럼 부정문을 가르지 않는다 — 정정인지
#   고쳐 말하기인지 서술로는 모른다.
#
# 받지 않는 것 — 요양급여ㆍ의료급여 홀로, '본인부담' 홀로(본인부담상한제ㆍ전액본인부담ㆍ산재
# 본인부담의료비), 비급여를 풀어 쓴 "급여 적용 안 되는"ㆍ"급여 외"ㆍ"급여 대상이 아닌", 상품 이름
# "급여 실손". "임의비급여 없음"ㆍ"3대비급여는 제외"는 급여만이라는 말이 아니다. "입원 중
# 비급여"의 '중'은 기간이라 금액 뒤의 '중'만 본다. 공단은 국민건강보험공단만(근로복지공단은 산재).
#
# 160건에서 이 표지가 읽은 사례는 2건이고 둘 다 실제로 급여 의료비 분쟁이다(본인부담상한제
# 초과액, 요양급여 기준상 급여의료비인 성장호르몬제). 첫 판은 짝을 좁게 잡아 "급여만"ㆍ
# "비급여: 없음"ㆍ"급여 80만원, 비급여 20만원"이 빠져나갔다(반박 검토, notes/050).
#
# **반복(`*`)을 맞붙이지 않는다.** "공백* 선택어? 공백*"처럼 붙여 두면 공백이 긴 입력에서 나눌 길이
# 제곱으로 늘어난다 — 첫 판은 "급여" 뒤 공백 10만 칸에 78초가 걸렸다(검토 HIGH). 선택어는 늘
# "(공백* 선택어)?"로 묶는다. `tests/test_rider_covered_only.py`가 긴 공백 입력의 시간을 잰다.
_GAP = r"[\s()\[\]:]*"
# 급여와 본인부담 사이 — "급여, 본인부담금", "급여/본인부담금", "급여의ㆍ에서ㆍ내ㆍ에 대한
# 본인부담금".
_LINK = r"[\s()\[\]:,/]*(?:(?:의|중|에서|내|해당|에\s*대한)\s*)?"
# 급여와 비급여를 잇는 말. 'ㆍ'(U+318D)는 NFKC가 U+119E로 바꿔 놓으므로 그쪽만 둔다.
_JOIN = r"(?:[·ᆞ・‧•∙、,/+&;~|-]|및|와|과|그리고|또는|이랑|랑|하고|외|에)"
# '비급여 없음'의 부정어 앞 — "비급여: 없음", "비급여(없음)", "비급여/없음", "비급여=0",
# "비급여—없음".
_NEG_GAP = r"[\s()\[\]:,/=—–―-]*"
# 적용ㆍ대상ㆍ해당 뒤의 부정 — 이것이 오면 비급여를 풀어 쓴 말이라 '급여' 표지로 읽지 않는다
# ("급여 적용 안 되는", "급여 대상이 아닌", "건강보험 적용 대상이 아닌"). 받는 쪽만 읽는 것이라
# 지급 쪽으로 새는 길이 아니다 — 거짓말로 '적용 안 된다'고 적으면 '비급여'라고 적은 것과 같다.
_NOT_NEGATED = (
    r"(?!\s*(?:(?:이|가|은|는|에)\s*)?(?:안|않|아[니닌님닙]|되지|불|제외|외|미|[xX×]"
    r"|대상\s*(?:(?:이|가)\s*)?(?:아|외|제외)))"
)
# '비급여' 표지를 같은 길이로 가린 글자. 가린 뒤에 찾아야 "비 급여 항목"의 '급여 항목'을 급여로
# 읽지 않는다. 사설 영역 글자라 `clean`이 입력에서 먼저 지운다 — 입력의 '▒' 같은 보이는 글자로
# 두면 그 글자를 앞에 붙여 표지를 막을 수 있었다(검토 LOW).
_MASK = chr(0xE000)
# 홀로 선 — 앞이 한글도, 가린 글자도 아니다. 가린 글자 앞을 막지 않으면 "임의비급여"의 둘째 칸부터
# '비급여'가 홀로 선 것처럼 읽힌다. 띄어 쓴 "급 여"도 이 막음 덕에 "지급 여부"가 되지 않는다.
_ALONE = rf"(?<![가-힣{_MASK}])"
_GEUPYEO = r"급\s*여"
# 급여 몫을 가리키는 짝이 뒤따르면 요양ㆍ의료ㆍ보험이 앞에 붙어도 받는다.
_PAYER = rf"(?:{_ALONE}|(?<=요양|의료|보험)){_GEUPYEO}"
# 부담 — 뒤에 률ㆍ율이 오면 뺀다. 본인부담률은 모든 영수증에 있는 값(구조화 입력 `copay_rate`)이라
# 급여 청구라는 말이 아니다.
_BURDEN = r"부담(?!\s*[률율])"
_AMOUNT = r"\d[\d,]*\s*(?:(?:만|천)\s*)?원"
_COVERED_RE = re.compile(
    "|".join(
        (
            # 급여 + 본인(환자)부담, 영수증의 급여 칸 이름.
            rf"{_PAYER}{_LINK}(?:일부\s*)?(?:본인|환자){_GAP}(?:일부\s*)?{_BURDEN}",
            rf"본인{_GAP}일부{_GAP}{_BURDEN}",
            rf"일부{_GAP}본인{_GAP}{_BURDEN}",
            rf"건강\s*보험{_GAP}(?:본인|환자){_GAP}{_BURDEN}",
            # 건강보험이 적용됐다는 말 — "적용되지 않는"ㆍ"적용 안 된"은 비급여라 받지 않는다.
            rf"(?:건강\s*보험|건보)(?:{_GAP}(?:이|가))?{_GAP}적용{_NOT_NEGATED}",
            # 공단은 국민건강보험공단만 — "근로복지공단 부담"은 산재다. "공단이 부담했어요",
            # "공단에서 80% 냈어요", "공단청구액"(공단부담금의 다른 이름)도.
            rf"(?:(?<![가-힣])|(?<=보험|건보))공단(?:{_GAP}(?:이|에서|측))?{_GAP}"
            rf"(?:\d+\s*%{_GAP})?(?:{_BURDEN}|냈|청구|몫)",
            # 보험자는 공단 — "피보험자 부담"은 아니다.
            rf"(?<![가-힣])보험자{_GAP}{_BURDEN}",
            # 급여 + 진료의 무엇 — 항목ㆍ부분ㆍ의료비ㆍ진료(비)ㆍ치료(비)ㆍ검사ㆍ수술ㆍ입원ㆍ통원ㆍ
            # 처방ㆍ약제ㆍ약값ㆍ비용ㆍ청구ㆍ몫, 급여비ㆍ급여분ㆍ급여만, 급여로 처리ㆍ인정.
            rf"{_PAYER}{_GAP}(?:항목|부분|의료비|진료비?|치료비?|검사|수술|입원|통원|처방"
            r"|약제|약값|비용|청구|몫)",
            rf"{_PAYER}(?:분|만|비(?![가-힣]))",
            rf"{_PAYER}(?:(?:으로|로){_GAP})?(?:처리|인정)",
            # 받는 쪽으로만 읽는 말 — 급여 적용ㆍ대상ㆍ해당. 요양ㆍ의료가 붙은 꼴은 처리결과 문장
            # ("요양급여 대상 수술방법", "요양급여 적용 여부")에 흔해 홀로 선 '급여'만 본다.
            rf"{_ALONE}{_GEUPYEO}{_GAP}(?:적용|대상|해당){_NOT_NEGATED}",
            # "사실 급여였어요", "급여입니다", "모두 급여".
            rf"{_ALONE}{_GEUPYEO}(?:였|이었|이에요|예요|입니다|이다|임)",
            rf"(?<![가-힣])(?:전부|모두)\s*{_GEUPYEO}(?!{_GAP}실손)",
            # 급여와 비급여를 함께 — 급여 + 금액, 급여ㆍ비급여, 비급여와 급여.
            # "비급여, 급여 외"는 비급여를 두 번 말한 것이다.
            rf"{_ALONE}{_GEUPYEO}{_GAP}(?:(?:금액|액){_GAP})?\d",
            rf"{_ALONE}{_GEUPYEO}{_GAP}(?:{_JOIN}{_GAP})?{_MASK}+",
            rf"{_ALONE}{_MASK}+{_GAP}(?:{_JOIN}{_GAP})?{_GEUPYEO}"
            rf"(?!{_GAP}(?:실손|외|적용|대상|제외))",
            # 전체 중 일부만 비급여 — "100만원 중 비급여", "그중 비급여", "비급여 30만원 포함".
            rf"(?:(?<=[\d만천백])원|{_ALONE}그){_GAP}(?:중|가운데){_GAP}{_MASK}",
            rf"{_ALONE}{_MASK}+{_GAP}(?:(?:금액|액){_GAP})?{_AMOUNT}{_GAP}(?:포함|별도)",
            # 홀로 선 '비급여'가 없다는 말. 부정어는 어미까지 삼킨다 — 사유에 '비급여 없'이
            # 아니라 '비급여 없이'로 적힌다(`word_at`이 조사로 보고 떼지 않게).
            rf"{_ALONE}{_MASK}+"
            rf"(?:{_GAP}(?:항목|진료비?|의료비|치료비?|비용|청구|부분|분|내역|금액|합계|총액|소계"
            r"|계|액))?"
            rf"(?:{_GAP}(?:은|는|이|가|도|를|을))?"
            rf"(?:{_GAP}(?:전혀|하나도|일절|일체))?"
            rf"{_NEG_GAP}"
            r"(?:(?:해당\s*(?:사항\s*)?(?:이\s*)?)?(?:없|無)[가-힣]*|해당\s*안"
            r"|아[니닌님닙냐녜닐녀][가-힣]*|0+(?![\d.,])\s*원?|₩\s*0+(?![\d.,])|영\s*원"
            r"|제외[가-힣]*|미\s*(?:포함|발생|해당)|불\s*포함|빼고|뺀|전무|무(?![가-힣])"
            r"|받지\s*않[가-힣]*|안\s*받[가-힣]*|[xX×](?![\w-]))",
        )
    )
)
# '비급여'에 금액을 달았는데 다른 금액도 적었으면 나머지는 급여다 — "진료비 100만원, 비급여 30만원".
# 금액이 그것 하나뿐이거나 같은 금액이면 섞였다고 보지 않는다 — "비급여 10만원 통원"은 비급여
# 청구다.
_ITEMIZED_RE = re.compile(rf"{_ALONE}{_MASK}+{_GAP}(?:(?:금액|액){_GAP})?{_AMOUNT}")


def noncovered_word(text: str) -> str | None:
    """'비급여'라고 말한 낱말. `clean`을 거친 글을 받는다.

    둘레 낱말을 붙이지 않고("급여ㆍ비급여"를 통째로 적으면 무엇을 가리키는지 흐려진다) 끼운
    기호만 뺀다 — "비-급여"는 '비급여'로 적는다.
    """
    match = _NONCOVERED_RE.search(text)
    return None if match is None else re.sub(_NONCOVERED_SEP, "", match.group(0))


def covered_word(text: str) -> str | None:
    """급여 몫을 가리키는 짝("급여 본인부담금", "비급여 항목 없음"). `clean`을 거친 글을 받는다.

    짝째로 적는다 — '급여'만 적으면 무엇을 읽었는지 모르고, 재심사에서 남긴 낱말
    (`held_treatment`)이 다시 표지로 읽혀야 한다.
    """
    masked = _NONCOVERED_RE.sub(lambda m: _MASK * len(m.group(0)), text)
    match = _COVERED_RE.search(masked) or _itemized(text, masked)
    if match is None:
        return None
    # 사유와 재심사 안내에 그대로 나가니 줄바꿈은 한 칸으로, NFKC가 바꾼 가운뎃점은 되돌린다.
    word = " ".join(word_at(text, *match.span()).split())
    return word.replace(_NFKC_MIDDLE_DOT, "ㆍ")


def _itemized(text: str, masked: str) -> re.Match[str] | None:
    """'비급여 30만원'과 다른 금액이 함께 적혔으면 그 자리. 아니면 None."""
    match = _ITEMIZED_RE.search(masked)
    if match is None:
        return None
    others = set(parse_amounts(text)) - set(parse_amounts(match.group(0)))
    return match if others else None
